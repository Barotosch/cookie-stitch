const languageKey='cookie-stitch-language';

function savedLanguage(){
 try{return globalThis.localStorage?.getItem(languageKey)==='de'?'de':'en';}
 catch{return 'en';}
}

export const language=savedLanguage();
const locale=language==='de'?'de-DE':'en-US';
const number=new Intl.NumberFormat(locale);
export const fmt=value=>number.format(value);
export const percent=(value,maximumFractionDigits=0)=>
 new Intl.NumberFormat(locale,{style:'percent',maximumFractionDigits}).format(value);

export function t(key,params={}){
 const message=messages[key]?.[language==='de'?1:0];
 if(message===undefined)throw new Error('Unknown translation: '+key);
 return message.replace(/\{(\w+)\}/g,(_,name)=>String(params[name]??''));
}

export class AppError extends Error {
 constructor(code){
  super(messages[code][1]);
  this.code=code;
 }
}

export function errorText(error,fallback='genericError'){
 return t(error instanceof AppError?error.code:fallback);
}

export function parseJson(text){
 try{return JSON.parse(text);}
 catch{throw new AppError('invalidJson');}
}

export function localizePage(doc=document){
 doc.documentElement.lang=language;
 for(const el of doc.querySelectorAll('[data-i18n]'))el.textContent=t(el.dataset.i18n);
 for(const attr of ['aria-label','title','placeholder','content']){
  const key='data-i18n-'+attr;
  for(const el of doc.querySelectorAll('['+key+']'))el.setAttribute(attr,t(el.getAttribute(key)));
 }
}

export function rememberLanguage(next){
 if(next==='en'||next==='de')localStorage.setItem(languageKey,next);
}
